export type PlanRoom = {
  /** Брошур дээрх дугаарлалт (1, 2, 3 …). */
  no: number;
  name: string;
  /** "м²"-гүй тоон утга — UI дээр нэгжийг нэмнэ. */
  area: string;
};

export type UnitPlan = {
  /** Танилцуулга дахь айлын дугаар (ж: "E-3"). */
  code: string;
  /** Өгөгдмөл аксонометр рендерүүд — админд `views` хоосон үлдсэн
   *  типэд lightbox-ыг ажиллуулахын тулд `mergeSiteContent` эндээс нөхнө. */
  views: string[];
  /** Давхрын хуваалт — тухайн айлыг тодруулсан бүтэн давхрын зураг
   *  (брошурын 2-р, 3-р хуудаснаас; `public/images/floorplan/`). */
  floorPlan: string;
  /** Аль давхруудад байдаг. */
  floors: string;
  rooms: string;
  /** Танилцуулгад заасан ашигтай талбай — өрөөнүүдийн нийлбэр.
   *  `site-content` болон `units.ts` дахь талбай мөн энэ утгаар
   *  нийцүүлэгдсэн тул самбарт давхардуулж харуулдаггүй. */
  area: string;
  /** Цонх харсан зүгүүд. */
  facing: string;
  /** Барилга дээрх байрлал — нэг өгүүлбэр. */
  spot: string;
  list: PlanRoom[];
};

const room = (no: number, name: string, area: string): PlanRoom => ({ no, name, area });

